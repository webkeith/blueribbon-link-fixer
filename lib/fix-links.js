const EMPTY_LINK = /<a\b[^>]*>(?:\s|&nbsp;| |<(strong|em|span|b|i)>(?:\s|&nbsp;| )*<\/\1>)*<\/a>/gi;

export function fixHtml(html) {
  const changes = [];
  let out = html.replace(MERGED_404, (full, rest) => {
    changes.push('merged 404 link -> /blog/septic-system-failure-signs');
    return `<a href="${B}/blog/septic-system-failure-signs"${rest}>`;
  });
  out = out.replace(EMPTY_LINK, m => {
    changes.push(`removed empty link ${m.slice(0, 120)}`);
    return '';
  });
  out = out.replace(/href="([^"]+)"/g, (full, href) => {
    const next = fixHref(href);
    if (!next) return full;
    changes.push(`${href}  ->  ${next}`);
    return `href="${next}"`;
  });
  return { out, changes };
}
