export function fixHref(href) {
  let raw = href.replace(/&amp;/g, '&');
  const original = raw;
  raw = stripChatgptUtm(raw);
  if (EXTERNAL[raw]) return EXTERNAL[raw];
  const g = raw.match(/^https:\/\/www\.google\.com\/search\?q=https:\/\/www\.blueribbonseptic\.com(\/[^&]*)/);
  if (g && GOOGLE_WRAPPED[g[1]]) return B + GOOGLE_WRAPPED[g[1]];
  if (/^https:\/\/www\.yelp\.com\/search\?/.test(raw) && raw.includes('\\&')) return raw.replace(/\\&/g, '&');
  const m = raw.match(/^https?:\/\/(?:www\.)?blueribbonseptic\.com(\/[^?#]*)?(\?[^#]*)?(#.*)?$/);
  if (!m) return raw === original ? null : raw;
  const path = m[1] || '/';
  if (m[2] && /^\?p=\d+$/.test(m[2])) return null;
  if (path.includes('%20http')) return null;
  const target = MAP[path] || path;
  const out = B + target + (m[2] || '') + (m[3] || '');
  return out === original ? null : out;
}

